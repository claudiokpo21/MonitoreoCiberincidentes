-- Monitor de Riesgo · calificaciones y opiniones de las apps (Google Play y App Store)
-- Ejecutar una sola vez en Supabase > SQL Editor. Solo crea objetos monitor_*.

-- 1) Tablas
create table if not exists public.monitor_apps (
  id text primary key,
  nombre text not null,
  play_id text,
  ios_id text,
  orden integer not null default 100,
  activo boolean not null default true
);
create table if not exists public.monitor_apps_lecturas (
  id bigint generated by default as identity primary key,
  app_id text not null references public.monitor_apps(id) on delete cascade,
  tienda text not null check (tienda in ('play', 'ios')),
  fecha timestamptz not null default now(),
  rating numeric(3,2),
  cantidad integer,
  version text,
  actualizada text,
  error text
);
create index if not exists monitor_apps_lecturas_app on public.monitor_apps_lecturas (app_id, tienda, fecha desc);
create table if not exists public.monitor_apps_resenas (
  id text primary key,
  app_id text not null references public.monitor_apps(id) on delete cascade,
  tienda text not null check (tienda in ('play', 'ios')),
  fecha timestamptz,
  autor text,
  estrellas smallint,
  titulo text,
  texto text,
  version text,
  respuesta text,
  respuesta_fecha timestamptz,
  tema text,
  leido timestamptz not null default now()
);
create index if not exists monitor_apps_resenas_fecha on public.monitor_apps_resenas (fecha desc);

-- 2) Permisos: solo los miembros del monitor leen; escribe únicamente el proceso automático
alter table public.monitor_apps enable row level security;
alter table public.monitor_apps_lecturas enable row level security;
alter table public.monitor_apps_resenas enable row level security;
drop policy if exists monitor_apps_ver on public.monitor_apps;
create policy monitor_apps_ver on public.monitor_apps for select to authenticated using (public.monitor_es_miembro());
drop policy if exists monitor_apps_lecturas_ver on public.monitor_apps_lecturas;
create policy monitor_apps_lecturas_ver on public.monitor_apps_lecturas for select to authenticated using (public.monitor_es_miembro());
drop policy if exists monitor_apps_resenas_ver on public.monitor_apps_resenas;
create policy monitor_apps_resenas_ver on public.monitor_apps_resenas for select to authenticated using (public.monitor_es_miembro());
grant select on public.monitor_apps, public.monitor_apps_lecturas, public.monitor_apps_resenas to authenticated;
revoke all on public.monitor_apps, public.monitor_apps_lecturas, public.monitor_apps_resenas from anon;

