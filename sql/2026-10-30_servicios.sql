-- Monitor de Riesgo · servicios monitoreados (bancos, billeteras, redes) compartidos por todo el equipo
-- Ejecutado el 2026-10-30. Solo crea objetos monitor_*; no toca tablas de otras aplicaciones.
create table if not exists public.monitor_servicios (
  id bigint generated by default as identity primary key,
  nombre text not null unique check (length(btrim(nombre)) between 1 and 60),
  grupo text not null default 'Otros' check (length(btrim(grupo)) between 1 and 60),
  web text,
  claves text[] not null default '{}',
  excluir text[] not null default '{}',
  dd text,
  destacado boolean not null default false,
  orden integer not null default 1000,
  activo boolean not null default true,
  agregado timestamptz not null default now(),
  "agregadoPor" text not null default ''
);
alter table public.monitor_servicios enable row level security;
drop policy if exists monitor_servicios_ver on public.monitor_servicios;
create policy monitor_servicios_ver on public.monitor_servicios for select to authenticated using (public.monitor_es_miembro());
drop policy if exists monitor_servicios_cargar on public.monitor_servicios;
create policy monitor_servicios_cargar on public.monitor_servicios for insert to authenticated with check (public.monitor_es_analista());
drop policy if exists monitor_servicios_editar on public.monitor_servicios;
create policy monitor_servicios_editar on public.monitor_servicios for update to authenticated using (public.monitor_es_analista()) with check (public.monitor_es_analista());
drop policy if exists monitor_servicios_borrar on public.monitor_servicios;
create policy monitor_servicios_borrar on public.monitor_servicios for delete to authenticated using (public.monitor_es_analista());
grant select, insert, update, delete on public.monitor_servicios to authenticated;
revoke all on public.monitor_servicios from anon;

-- Firma quién lo agregó y registra la actividad
create or replace function public.monitor_servicios_alta() returns trigger
language plpgsql security definer set search_path to 'public' as $$
begin
  if auth.uid() is not null then
    new.agregado := now();
    select coalesce(nombre, '') into new."agregadoPor" from public.monitor_perfiles where user_id = auth.uid();
  end if;
  new.nombre := btrim(new.nombre); new.grupo := btrim(new.grupo);
  return new;
end; $$;
drop trigger if exists monitor_servicios_alta on public.monitor_servicios;
create trigger monitor_servicios_alta before insert on public.monitor_servicios for each row execute function public.monitor_servicios_alta();

create or replace function public.monitor_servicios_log() returns trigger
language plpgsql security definer set search_path to 'public' as $$
begin
  if tg_op = 'INSERT' then perform public.monitor_log('servicio_alta', new.nombre, jsonb_build_object('grupo', new.grupo, 'web', new.web));
  elsif tg_op = 'UPDATE' then perform public.monitor_log('servicio_edicion', new.nombre, jsonb_build_object('grupo', new.grupo, 'web', new.web, 'activo', new.activo));
  else perform public.monitor_log('servicio_baja', old.nombre, jsonb_build_object('grupo', old.grupo)); end if;
  return null;
end; $$;
drop trigger if exists monitor_servicios_log on public.monitor_servicios;
create trigger monitor_servicios_log after insert or update or delete on public.monitor_servicios for each row execute function public.monitor_servicios_log();
revoke execute on function public.monitor_servicios_alta() from public, anon, authenticated;
revoke execute on function public.monitor_servicios_log() from public, anon, authenticated;

